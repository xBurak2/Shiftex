// ─── Mevcut dil ───
let currentLang = localStorage.getItem('sx_lang') || 'tr';

function getLang() { return currentLang; }

/**
 * Çeviri fonksiyonu — değişken interpolation destekler.
 * t('mydash.welcome', { name: 'Mehmet' })
 */
function t(key, vars) {
  const dict = I18N[currentLang] || I18N.tr;
  let str = dict[key] ?? I18N.tr[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.replaceAll('{' + k + '}', vars[k]);
    });
  }
  return str;
}

/**
 * DOM içindeki tüm data-i18n attribute'larını günceller.
 *  - data-i18n="key"               → textContent
 *  - data-i18n-placeholder="key"   → placeholder
 *  - data-i18n-title="key"         → title (tooltip)
 *  - data-i18n-html="key"          → innerHTML (dikkatli kullan)
 */
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  // <html lang="..."> attribute'u da güncelle
  document.documentElement.lang = currentLang;
}

/**
 * Dili değiştirir, kaydeder, DOM'u günceller.
 * Sayfa yenilemeden anında etki eder.
 */
function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('sx_lang', lang);
  applyI18n();
  // Etkin olan dinamik içerikleri yeniden yükle
  if (typeof window.onLanguageChanged === 'function') {
    try { window.onLanguageChanged(lang); } catch (_) {}
  }
}

